package com.graduation.kas.tadarab.Student.TrainingArea;

public class TrainingArea {
    String id,training_area,address;

    public TrainingArea() {
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getTraining_area() {
        return training_area;
    }

    public void setTraining_area(String training_area) {
        this.training_area = training_area;
    }

    public String getAddress() {
        return address;
    }

    public void setAddress(String address) {
        this.address = address;
    }
}
